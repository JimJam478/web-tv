#!/usr/bin/env bash
# Builds <id>.apk from app.properties (or the config file given), without Gradle:
# aapt2 -> javac -> d8 -> zipalign -> apksigner. Needs a JDK (17+) and the Android SDK (build-tools 34+, a platform).
# Install: adb install -r <id>.apk
set -euo pipefail
cd "$(dirname "$0")"
CONFIG="${1:-app.properties}"
die() { echo "error: $*" >&2; exit 1; }

[ -f "$CONFIG" ] || die "$CONFIG not found. Start from the example: cp app.properties.example app.properties"
get() {   # value of key $1 in the config: first "key = value" line, '#' lines ignored, value may contain '='
  sed -n "s/^[[:space:]]*$1[[:space:]]*=[[:space:]]*//p" "$CONFIG" | head -1 | sed 's/[[:space:]]*$//'
}
NAME="$(get name)"; URL="$(get url)"; ID="$(get id)"; ICON="$(get icon)"; CROP="$(get icon_crop)"
WIDTH="$(get page_width)"; WIDTH="${WIDTH:-1920}"
DESKTOP_UA="$(get desktop_ua)"; DESKTOP_UA="${DESKTOP_UA:-false}"

[ -n "$NAME" ] && [ ${#NAME} -le 50 ] || die "name: 1 to 50 characters"
[[ "$URL" =~ ^https?://[^[:space:]\"\\]+$ ]] || die "url: must start with http:// or https://, no spaces or quotes"
[[ "$ID" =~ ^[a-zA-Z][a-zA-Z0-9_]*(\.[a-zA-Z][a-zA-Z0-9_]*)+$ ]] \
  || die "id: like com.yourname.mysite (letters, digits, _, at least one dot); it must be unique per app"
[[ "$WIDTH" =~ ^[0-9]+$ ]] && [ "$WIDTH" -ge 320 ] && [ "$WIDTH" -le 3840 ] || die "page_width: a number, 320 to 3840"
[[ "$DESKTOP_UA" =~ ^(true|false)$ ]] || die "desktop_ua: true or false"
[ -z "$ICON" ] || [ -f "$ICON" ] || die "icon: $ICON not found"
[ -z "$CROP" ] || [[ "$CROP" =~ ^[0-9]+\ +[0-9]+\ +[0-9]+$ ]] || die "icon_crop: three numbers, x y size"

SDK="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-}}"
if [ -z "$SDK" ]; then
  for d in "$HOME/Library/Android/sdk" "$HOME/Android/Sdk" /opt/homebrew/share/android-commandlinetools; do
    if [ -d "$d/build-tools" ]; then SDK="$d"; break; fi
  done
fi
[ -n "$SDK" ] && [ -d "$SDK/build-tools" ] || die "Android SDK not found. Set ANDROID_HOME (see README)."
BT="$SDK/build-tools/$(ls "$SDK/build-tools" | sort -V | tail -1)"
AJ="$(ls -d "$SDK"/platforms/android-*/android.jar | sort -V | tail -1)"

# First build: fetch the ad lists (the installed app then refreshes its own copy weekly).
[ -f app/assets/hosts.txt ] && [ -f app/assets/hide.css ] || ./update-blocklist.sh

rm -rf out && mkdir -p out/gen/app/webtv out/classes out/res/values
cat > out/gen/app/webtv/Config.java <<EOF
package app.webtv;

/** Generated by build.sh from $CONFIG. */
final class Config {
    static final String URL = "$URL";
    static final int PAGE_WIDTH = $WIDTH;
    static final boolean DESKTOP_UA = $DESKTOP_UA;
}
EOF
# Android string resource: XML-escape, then backslash-escape quotes and a leading @ or ?.
ESCAPED="$(printf '%s' "$NAME" | sed -e 's/\\/\\\\/g' -e 's/&/\&amp;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g' \
  -e "s/'/\\\\'/g" -e 's/"/\\"/g' -e 's/^\([@?]\)/\\\1/')"
printf '<resources><string name="app_name">%s</string></resources>\n' "$ESCAPED" > out/res/values/strings.xml
# shellcheck disable=SC2086
java tools/Art.java out/res "$NAME" ${ICON:+"$ICON"} $CROP

"$BT/aapt2" compile --dir out/res -o out/res.zip
"$BT/aapt2" link -o out/base.apk -I "$AJ" -A app/assets --manifest app/AndroidManifest.xml --java out/gen out/res.zip \
  --rename-manifest-package "$ID" --min-sdk-version 26 --target-sdk-version 33
javac -nowarn -Xlint:-options -source 8 -target 8 -bootclasspath "$AJ" -classpath "$AJ" \
  -encoding UTF-8 -d out/classes $(find app/src out/gen -name '*.java')
"$BT/d8" --release --min-api 26 --lib "$AJ" --output out $(find out/classes -name '*.class')
(cd out && zip -qj base.apk classes.dex)
"$BT/zipalign" -f -p 4 out/base.apk out/aligned.apk

# Your own signing key, made on the first build. Keep it: updates to an installed app must use the same key.
if [ ! -f release.keystore ]; then
  keytool -genkeypair -keystore release.keystore -alias webtv -keyalg RSA -keysize 2048 -validity 20000 \
    -storepass webtv1 -keypass webtv1 -dname "CN=Web TV" >/dev/null 2>&1
fi
"$BT/apksigner" sign --ks release.keystore --ks-pass pass:webtv1 --key-pass pass:webtv1 --out "$ID.apk" out/aligned.apk
echo "Built $ID.apk ($(du -h "$ID.apk" | cut -f1)): \"$NAME\" opens $URL"
echo "Install: adb install -r $ID.apk"
